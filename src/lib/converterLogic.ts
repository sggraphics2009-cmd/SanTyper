/**
 * Generates an HTML representation of the converted text, applying standard sans-serif
 * fonts to English/Latin words, and DL-Manel font to Sinhala converted characters.
 * This ensures that pasting into Word/Google Docs maintains English characters correctly.
 */
export function getRichTextHTML(inputText: string, mode: "unicode-to-legacy" | "legacy-to-unicode", customFontName?: string, overrides?: Array<{ find: string, replace: string }>, profile?: "DL_SERIES" | "FM_SERIES"): string {
    const escapeHtml = (str: string) => {
        return str
            .replace(/&/g, "&amp;")
            .replace(/</g, "&lt;")
            .replace(/>/g, "&gt;")
            .replace(/"/g, "&quot;")
            .replace(/'/g, "&#039;")
            .replace(/\n/g, "<br>");
    };

    if (mode === "legacy-to-unicode") {
        const converted = dlManelToUnicode(inputText, overrides, profile);
        return `<span style="font-family: 'Iskoola Pota', 'Nirmala UI', sans-serif;" lang="si-LK">${escapeHtml(converted)}</span>`;
    }

    // Split by English alphanumeric words + spaces + basic punctuation to keep them together in English font
    // We use a regex that groups English letters and numbers along with their internal spaces/punctuation
    const chunks = inputText.split(/([a-zA-Z0-9]+(?:[\s\.!?,;:''"()\[\]{}]+[a-zA-Z0-9]+)*)/);
    
    let html = "";
    for (const chunk of chunks) {
        if (!chunk) continue;
        
        if (/[a-zA-Z0-9]/.test(chunk)) {
            // Keep English words exactly as they are in an English font
            html += `<span style="font-family: Arial, Helvetica, sans-serif;" lang="en-US">${escapeHtml(chunk)}</span>`;
        } else {
            // Convert Sinhala parts to Legacy Font
            const converted = unicodeToDlManel(chunk, overrides, profile);
            const legacyFont = customFontName ? `'${customFontName}', 'DL-Manel'` : `'DL-Manel', 'DL Manel', 'FMAbhaya'`;
            // Word uses mso-bidi-font-family and lang="en-US" ensures Word won't auto-switch the font for legacy ASCII mappings.
            html += `<span style="font-family: ${legacyFont}, sans-serif; mso-ascii-font-family: ${legacyFont}; mso-hansi-font-family: ${legacyFont}; mso-bidi-font-family: ${legacyFont}; font-size: 1.1em;" lang="en-US">${escapeHtml(converted)}</span>`;
        }
    }
    
    return html;
}
