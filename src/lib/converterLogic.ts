    text = text.replace(/\u0DDC\u0DCA/g, "\u0DDD");
    // Decomposed O short (kombuva + aelapilla) => O short
    text = text.replace(/\u0DD9\u0DCF/g, "\u0DDC");
    // Decomposed E long (kombuva + halanta) => E long
    text = text.replace(/\u0DD9\u0DCA/g, "\u0DDA");
    // Decomposed Au (kombuva + gayanukitta/diga gayanukitta) => Au
    text = text.replace(/\u0DD9[\u0DF2\u0DF3]/g, "\u0DDE");
    // Double kombuva => Ai (kombu deka)
    text = text.replace(/\u0DD9\u0DD9/g, "\u0DDB");
    // Standalone Diga Gayanukitta (U+0DF3) normalize to U+0DF2
    text = text.replace(/\u0DF3/g, "\u0DF2");
    // Double vowel marks normalization
    text = text.replace(/\u0DD8\u0DD8/g, "\u0DF2");
    text = text.replace(/\u0DD2\u0DD2/g, "\u0DD3");
    text = text.replace(/\u0DD4\u0DD4/g, "\u0DD6");
    text = text.replace(/\u0DD0\u0DD0/g, "\u0DD1");
    text = text.replace(/\u0DCF\u0DCF/g, "\u0DCF");

